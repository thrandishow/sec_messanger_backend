CREATE TABLE IF NOT EXISTS users (
    id text PRIMARY KEY, nickname text UNIQUE NOT NULL CHECK (nickname = lower(nickname)),
    salt text NOT NULL, password_hash text NOT NULL, created_at bigint NOT NULL,
    role text NOT NULL DEFAULT 'member', department text, active integer NOT NULL DEFAULT 1
);
CREATE TABLE IF NOT EXISTS sessions (
    token_hash text PRIMARY KEY, user_id text NOT NULL REFERENCES users ON DELETE CASCADE,
    expires_at bigint NOT NULL
);
CREATE INDEX IF NOT EXISTS sessions_expiry ON sessions(expires_at);
CREATE TABLE IF NOT EXISTS departments (channel text PRIMARY KEY, name text NOT NULL);
CREATE TABLE IF NOT EXISTS files (
    id text PRIMARY KEY, owner text NOT NULL REFERENCES users, scope text NOT NULL,
    target text NOT NULL, name text NOT NULL, size bigint NOT NULL, content bytea NOT NULL, created_at bigint NOT NULL
);
CREATE TABLE IF NOT EXISTS messages (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sender text NOT NULL REFERENCES users, recipient text REFERENCES users,
    target text NOT NULL, text text NOT NULL, time text NOT NULL,
    file_id text UNIQUE REFERENCES files
);
CREATE INDEX IF NOT EXISTS messages_channel ON messages(target,id);
CREATE INDEX IF NOT EXISTS messages_direct ON messages(sender,recipient,id);
CREATE TABLE IF NOT EXISTS audit (
    id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    time text NOT NULL, actor text, action text NOT NULL, subject text, ip text NOT NULL
);
CREATE TABLE IF NOT EXISTS storage_migrations (name text PRIMARY KEY, completed_at timestamptz NOT NULL DEFAULT now());
